// Pruebas del motor de ausencias. Ejecutar: node tests/ausencias.test.js
global.window = {};
require('../js/params.js');
const T = window.RRHH_PARAMS.ausencias.tipos;
const A = require('../js/engines/ausencias.js');
let fallos = 0, total = 0;
const ok = (n, c, x = '') => { total++; if (!c) fallos++; console.log(`${c ? '✔' : '✘'} ${n}${!c && x !== '' ? '  → ' + x : ''}`); };
const hoy = '2026-10-21';
const it = { id: 1, tipo: 'it', desde: '2026-10-10', hastaPrevista: '2026-10-30' };
ok('IT en curso', A.estado(it, hoy) === 'en-curso');
ok('Programada si empieza después de hoy', A.estado({ ...it, desde: '2026-11-01', hastaPrevista: '2026-11-10' }, hoy) === 'programada');
ok('Vuelta sin confirmar si pasó la fecha prevista', A.estado({ ...it, hastaPrevista: '2026-10-20' }, hoy) === 'sin-confirmar');
ok('Finalizada con fin real', A.estado({ ...it, finReal: '2026-10-18' }, hoy) === 'finalizada');
ok('Sin fecha prevista: en curso indefinidamente', A.estado({ id: 2, tipo: 'it', desde: '2026-09-01' }, hoy) === 'en-curso');
ok('Vuelta prevista = día siguiente al último día', A.vueltaPrevista(it) === '2026-10-31');
ok('Días transcurridos (12) y previstos (21)', A.dias(it, hoy).transcurridos === 12 && A.dias(it, hoy).previstos === 21, JSON.stringify(A.dias(it, hoy)));
ok('Días de una finalizada', A.dias({ ...it, finReal: '2026-10-15' }, hoy).transcurridos === 6);
const t = A.tarea(it, 'Lucía Martín', T[0], 5);
ok('Tarea de reincorporación 5 días antes de la vuelta', t.fecha === '2026-10-26' && t.titulo === 'Reincorporación de Lucía Martín (31/10)', JSON.stringify(t));
ok('Sin tarea si no hay fecha prevista o ya volvió', A.tarea({ ...it, hastaPrevista: '' }, 'X', T[0], 5) === null && A.tarea({ ...it, finReal: '2026-10-20' }, 'X', T[0], 5) === null);
ok('Reducción: tarea de fin, no de reincorporación', A.tarea({ id: 3, tipo: 'reduccion', desde: '2026-01-01', hastaPrevista: '2026-12-31' }, 'Ana', A.tipoDe(T, 'reduccion'), 5).titulo === 'Fin de reducción de jornada de Ana (31/12)');
const lista = [it, { id: 3, tipo: 'reduccion', desde: '2026-01-01', hastaPrevista: '2026-12-31' }, { id: 4, tipo: 'excedencia', desde: '2026-03-01', finReal: '2026-06-30' }, { id: 5, tipo: 'it', desde: '2026-09-01' }];
ok('Ausentes hoy: IT con fecha y IT sin fin (no la reducción ni la finalizada)', A.ausentesEn(lista, hoy, T, hoy).map(a => a.id).join() === '1,5');
ok('Ausente en una fecha pasada (excedencia en abril)', A.ausentesEn(lista, '2026-04-15', T, hoy).map(a => a.id).join() === '3,4'.replace('3,', ''));
ok('IT sin fin no aparece en fechas futuras', !A.ausentesEn(lista, '2026-11-15', T, hoy).some(a => a.id === 5));
ok('Próximas vueltas en 30 días', A.proximasVueltas(lista, hoy, 30).map(a => a.id).join() === '1');
ok('Días sin devengo (excedencia mar-jun = 122 días)', A.diasSinDevengo(lista, T, 2026) === 122, A.diasSinDevengo(lista, T, 2026));
ok('Sin devengo hasta una fecha (hasta 31/03 = 31 días)', A.diasSinDevengo(lista, T, 2026, '2026-03-31') === 31);
ok('Las IT no restan vacaciones', A.diasSinDevengo([it], T, 2026) === 0);
ok('Validar: fechas al revés', A.validar({ empleadoId: 1, tipo: 'it', desde: '2026-10-10', hastaPrevista: '2026-10-01' }).length === 1);
ok('Validar: falta todo', A.validar({}).length === 3);
ok('Todos los tipos tienen acciones', T.every(x => x.acciones && x.acciones.length));
console.log(fallos ? `\n${fallos} de ${total} pruebas fallidas` : `\nTodas las pruebas correctas (${total})`);
process.exit(fallos ? 1 : 0);
